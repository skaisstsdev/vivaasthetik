// Убирает из текста пользователя явные персональные данные до отправки в OpenAI:
// e-mail, телефоны, IBAN, номера карт. Имена так не поймать, поэтому бот ещё и просит
// не писать личное и медицинское (см. системный промпт).
export function scrubPersonalData(text: string): string {
  return text
    .replace(/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/gi, '[e-mail]')
    .replace(/\b[A-Z]{2}\d{2}(?:\s?[A-Z0-9]{4}){3,7}(?:\s?[A-Z0-9]{1,4})?\b/g, '[iban]')
    .replace(/\b(?:\d[ -]?){13,19}\b/g, '[nummer]')
    .replace(/(?<!\w)\+?\d[\d\s()/.-]{7,}\d/g, '[tel]');
}
